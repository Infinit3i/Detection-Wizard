//! MITRE ATT&CK technique (TTP) catalog for the rules screen.
//!
//! Full enterprise-attack matrix (techniques + sub-techniques), generated
//! from the official MITRE CTI STIX bundle so every published ATT&CK ID is
//! filterable here. Tactics reflect the current (v17+) taxonomy, which
//! split the old "Defense Evasion" tactic into "Stealth" and "Defense
//! Impairment". Selecting entries activates technique filtering (see
//! `filter.rs`); selecting none leaves the filter inactive so every rule
//! is kept. Parent codes also match their subtechniques (T1059 keeps
//! T1059.001).

pub struct TtpDef {
    /// ATT&CK ID, e.g. "T1059" or "T1566.001"
    pub id: &'static str,
    /// technique name as shown in ATT&CK
    pub name: &'static str,
    /// tactic used as the section header
    pub tactic: &'static str,
}

const fn t(id: &'static str, name: &'static str, tactic: &'static str) -> TtpDef {
    TtpDef { id, name, tactic }
}

