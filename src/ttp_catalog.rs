#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn no_duplicate_id_tactic_pairs() {
        let mut pairs: Vec<(&str, &str)> = TTP_CATALOG.iter().map(|d| (d.id, d.tactic)).collect();
        let before = pairs.len();
        pairs.sort();
        pairs.dedup();
        assert_eq!(
            before,
            pairs.len(),
            "duplicate (id, tactic) pairs in TTP catalog"
        );
    }

    #[test]
    fn covers_full_enterprise_matrix() {
        // Sanity check: the full MITRE ATT&CK enterprise matrix (techniques +
        // sub-techniques, current 15-tactic taxonomy) is in the 800s; this
        // guards against an accidental truncation regressing the catalog
        // back to the old hand-picked ~150-entry subset.
        assert!(
            TTP_CATALOG.len() > 800,
            "expected the full ATT&CK matrix, got {} entries",
            TTP_CATALOG.len()
        );
    }

    #[test]
    fn every_id_starts_with_t_and_every_field_is_non_empty() {
        for def in TTP_CATALOG {
            assert!(def.id.starts_with('T'), "bad id: {}", def.id);
            assert!(!def.name.is_empty(), "empty name for {}", def.id);
            assert!(!def.tactic.is_empty(), "empty tactic for {}", def.id);
        }
    }
}
